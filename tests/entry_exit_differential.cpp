// Entry/exit semantics differential — three back ends, one machine.
//
// Drives the SAME small machine (tests/fixtures/entry_exit_trace.fsm) through all three
// implementations and records the ORDER of every action call (exit/action/enter, labeled).
// Characterization only: it records and compares; it does not pin a winner.
//
// This is the RED evidence for review finding #1 (entry/exit semantics disagree across
// the fleet).  All three readings disagree, which is the proof.
//
// fsmgine::FSM (interpreted) — action runs FIRST, then exit, then enter.
//   Self-transitions run NEITHER exit nor enter (FSM.hpp:429, current_state_ != target_state).
//
// fsmgine::compiled::Machine — no entry/exit concept at all.
//
// fsmtable-gen generated code — exit → action → entry (ENTRY_EXIT.md:39).
//   Self-transitions are external: both exit and entry run (Q13).

#include "FSMgine/FSM.hpp"
#include "FSMgine/FSMBuilder.hpp"
#include "FSMgine/compiled/Machine.hpp"

// Generated by fsmtable-gen from tests/fixtures/entry_exit_trace.fsm
#include "fsm_entry_exit_trace.hpp"

#include <gtest/gtest.h>

#include <string>
#include <vector>

// ---- shared trace log (file scope — accessed by both anonymous and fsmtable_generated) ----

std::vector<std::string> g_trace;

void reset_trace() { g_trace.clear(); }

std::string format_trace(const std::vector<std::string>& trace) {
    std::string out;
    for (const auto& entry : trace) {
        if (!out.empty())
            out += ", ";
        out += entry;
    }
    return "[" + out + "]";
}

// ---- 3. fsmtable-gen generated code ----
//
// The generated header declares action functions; we define them here.
// These MUST be in the real fsmtable_generated namespace (matching the header's declarations).

namespace fsmtable_generated {
void on_ab(const TraceTestEvent&) { g_trace.push_back("action:on_ab"); }
void on_bb(const TraceTestEvent&) { g_trace.push_back("action:on_bb"); }
void on_ba(const TraceTestEvent&) { g_trace.push_back("action:on_ba"); }
void on_entry_a(const TraceTestEvent&) { g_trace.push_back("enter:on_entry_a"); }
void on_exit_a(const TraceTestEvent&) { g_trace.push_back("exit:on_exit_a"); }
void on_entry_b(const TraceTestEvent&) { g_trace.push_back("enter:on_entry_b"); }
void on_exit_b(const TraceTestEvent&) { g_trace.push_back("exit:on_exit_b"); }
} // namespace fsmtable_generated

namespace {

using fsmtable_generated::TraceTestEvent;
using fsmtable_generated::TraceTestKind;
using fsmtable_generated::TraceTestState;

// ---- 1. fsmgine::FSM (interpreted) ----

std::vector<std::string> run_interpreted() {
    reset_trace();
    fsmgine::FSM<TraceTestEvent> fsm;

    // Entry/exit registered on the states via the builder (delegates to FSM).
    fsm.get_builder()
        .onEnter("A", [](const TraceTestEvent&) { g_trace.push_back("enter:on_entry_a"); })
        .onExit("A", [](const TraceTestEvent&) { g_trace.push_back("exit:on_exit_a"); })
        .onEnter("B", [](const TraceTestEvent&) { g_trace.push_back("enter:on_entry_b"); })
        .onExit("B", [](const TraceTestEvent&) { g_trace.push_back("exit:on_exit_b"); })
        .from("A")
        .predicate([](const TraceTestEvent& e) { return e.kind == TraceTestKind::go; })
        .action([](const TraceTestEvent&) { g_trace.push_back("action:on_ab"); })
        .to("B");

    fsm.get_builder()
        .from("B")
        .predicate([](const TraceTestEvent& e) { return e.kind == TraceTestKind::loop; })
        .action([](const TraceTestEvent&) { g_trace.push_back("action:on_bb"); })
        .to("B");

    fsm.get_builder()
        .from("B")
        .predicate([](const TraceTestEvent& e) { return e.kind == TraceTestKind::back; })
        .action([](const TraceTestEvent&) { g_trace.push_back("action:on_ba"); })
        .to("A");

    fsm.setInitialState("A");
    reset_trace(); // setInitialState fires onEnter for A — not part of the transition trace

    TraceTestEvent e1{TraceTestKind::go, 0};
    TraceTestEvent e2{TraceTestKind::loop, 0};
    TraceTestEvent e3{TraceTestKind::back, 0};

    fsm.process(e1); // A → B
    fsm.process(e2); // B → B (self-transition)
    fsm.process(e3); // B → A

    return g_trace;
}

// ---- 2. compiled::Machine (plain — no entry/exit) ----

// Function pointers (compiled::Machine cannot use capturing lambdas).
void compiled_action_ab(const TraceTestEvent&) { g_trace.push_back("action:on_ab"); }
void compiled_action_bb(const TraceTestEvent&) { g_trace.push_back("action:on_bb"); }
void compiled_action_ba(const TraceTestEvent&) { g_trace.push_back("action:on_ba"); }

std::vector<std::string> run_compiled_plain() {
    reset_trace();

    std::vector<fsmgine::compiled::Transition<TraceTestState, TraceTestEvent>> rows = {
        {TraceTestState::A, TraceTestKind::go, false, fsmgine::compiled::Op::Eq, 0,
         TraceTestState::B, &compiled_action_ab},
        {TraceTestState::B, TraceTestKind::loop, false, fsmgine::compiled::Op::Eq, 0,
         TraceTestState::B, &compiled_action_bb},
        {TraceTestState::B, TraceTestKind::back, false, fsmgine::compiled::Op::Eq, 0,
         TraceTestState::A, &compiled_action_ba},
    };

    fsmgine::compiled::Machine<TraceTestState, TraceTestEvent> machine{
        &TraceTestEvent::kind, &TraceTestEvent::value, std::move(rows)};
    machine.setInitialState(TraceTestState::A);
    reset_trace();

    TraceTestEvent e1{TraceTestKind::go, 0};
    TraceTestEvent e2{TraceTestKind::loop, 0};
    TraceTestEvent e3{TraceTestKind::back, 0};
    machine.process(e1);
    machine.process(e2);
    machine.process(e3);

    return g_trace;
}

// ---- 3. generated (run_generated calls makeTraceTest) ----

std::vector<std::string> run_generated() {
    reset_trace();
    auto machine = fsmtable_generated::makeTraceTest();
    reset_trace(); // makeTraceTest calls setInitialState — no entry/exit on compiled back end

    TraceTestEvent e1{TraceTestKind::go, 0};
    TraceTestEvent e2{TraceTestKind::loop, 0};
    TraceTestEvent e3{TraceTestKind::back, 0};
    machine.process(e1);
    machine.process(e2);
    machine.process(e3);

    return g_trace;
}

} // namespace

TEST(EntryExitDifferential, InterpretedMatchesGenerated) {
    const auto interpreted = run_interpreted();
    const auto compiled_plain = run_compiled_plain();
    const auto generated = run_generated();

    const std::string msg = "\n  fsmgine::FSM (interpreted): " + format_trace(interpreted)
                            + "\n  compiled::Machine (plain):  " + format_trace(compiled_plain)
                            + "\n  fsmtable-gen (generated):   " + format_trace(generated)
                            + "\n\n  RULING (t_ba3c6d56): interpreted and generated must agree"
                            + "\n  (exit -> action -> entry; self-transitions external)."
                            + "\n  compiled::Machine has no entry/exit hooks (A2 caveat) — it is"
                            + "\n  excluded from the equality check.";

    // RULING (t_ba3c6d56): the fleet standard is exit -> action -> entry with
    // external self-transitions.  fsmgine::FSM (interpreted) and fsmtable-gen
    // (generated) must agree.  compiled::Machine has no entry/exit concept at
    // all — that is the A2 caveat documented in Machine.hpp — so it is
    // deliberately excluded from this regression guard.
    EXPECT_EQ(interpreted, generated) << msg;
}